/**
 * ── 规则 F：注释里不许写没人能核的裁定计数 ─────────────────────────────────
 *
 * **它为什么在这里**：本仓复述同一条裁定的地方有好几处，其中两处引的是**同一句**话，
 * 一个说三次、一个说四回——**2:2 互相打架**。仓里已有的裁定原文写在
 * `tests/unit/admin/probe-guard.test.ts` 里「出站探测：两条端点的单一真源（源码级）」
 * 上方那一段：**「从来没有人列出过是哪三次……要么列出来，要么把计数删掉」**。
 * 那次裁定只落到了两处，剩下几处照旧带着计数。**光改几处不立守卫，下一期还会长回来。**
 * 一个没人能核的计数比一句过期的话更糟，而它就写在要推公开仓的源码注释里。
 *
 * ⚠️ **本期一律「把计数删掉」，不走「列出来」那一支**：那份清单本身又会是一张
 * 没人守的手写表，等于把同一个病换个地方长。
 *
 * ⚠️ **段级豁免标记（`IGNORE_MARKER`）对这条规则有效，而且是必需的**：本仓唯一一份裁定原文
 * 就写在「引用上一版原文 + 说明计数已删」的那两段里，那两段字面上必然带着计数
 * （计数在那里是**被引用的对象**，不是本仓在主张一个数字）。把它们改干净等于毁掉
 * 那份原文。**豁免不许变成一张没人守的名册**：脚本会把「落在豁免段里的裁定计数」
 * 逐处报出来（`COMMENT_REFS_LIST_IGNORED=1` 时的 `counted-ruling-exempt` 行），
 * `tests/unit/check-comment-refs.test.ts` 的
 * 「裁定计数的豁免逐处列名 —— 多一处就红」把它钉成手写清单。
 *
 * ⚠️ **上面那句刻意写成 `IGNORE_MARKER` 而不是标记本身**：写成标记本身的话，
 * **这一段会把自己豁免掉**，连带它里面那条活着的名字锚一起脱离校验
 * ——本任务实测踩过一次（豁免数从既有的那几处悄悄多出一处，而多出来的那一处
 * 里躺着一条真指向）。同一条坑本文件在 `IGNORE_FILE_RE` 那一行也踩过。
 *
 * ⚠️ **数词表里必须有「两」**（本任务复评当场抓到的漏网）：中文里重新写这句话时
 * 最自然的数词就是「两」，而第一版的字符类只有 `一二三四五六七八九十`，
 * 于是**「两」那种写法当场放行、只有「二」那种才红**——一条防「删干净之后
 * 重新长回来」的规则，偏偏漏掉了重新长回来时最可能用的那个字。
 * **这一段刻意不把那两个句子逐字写出来**：写出来这条规则会当场打中它自己
 * （与规则 D 上方那句「举例一律写成 `第 N 行`」同一条口径）。
 * 逐字的那两个句子在 `tests/unit/check-comment-refs.test.ts`
 * 「⇒ exit 1，报文指向仓里已有的那条裁定」那张表里（`it.each` 的夹具，不是散文）。
 *
 * ⚠️ **它认不得什么，明写**：判据只认「裁过 + 数量 + 次/回」这一种句式。
 * 换成「裁定过 N 轮」「判过 N 回合」「裁过 N 遍」「裁了 N 次」就绕过去了
 * ——与规则 B 上方那句边界同一条口径：给「顺手写下一个没人能核的计数」加一道摩擦，
 * 不给「刻意绕开」设一道墙。**这条边界与规则 E 那条一样是断言、不是散文**：
 * `tests/unit/check-comment-refs.test.ts` 的
 * 「已知认不得：%s ⇒ 今天放行（边界是断言，不是散文）」在规则 F 名下也有一张，
 * 判据哪天放宽收进了其中一条，那一格会变红，逼人把它从表里挪走并改这一段。
 * ⚠️ **`docs/` 同样刻意不动**，与规则 E 是同一条边界。
 */
const COUNTED_RULING_SRC = "裁过\\s*(?:\\d+|[一二三四五六七八九十两]+)\\s*[次回]";
const COUNTED_RULING_RE = new RegExp(COUNTED_RULING_SRC, "g");

const errors = [];
const ignored = [];
/** 落在**豁免段**里的裁定计数，逐处记名——见规则 F 上方那段「豁免不许变成一张没人守的名册」。 */
const countedRulingExempt = [];
let checked = 0;
let claimChecked = 0;

const lineCache = new Map();
function linesOf(rel) {
  if (!lineCache.has(rel)) {
    lineCache.set(rel, readFileSync(join(ROOT, rel), "utf8").split("\n"));
  }
  return lineCache.get(rel);
}

for (const dir of SCAN_DIRS) {
  for (const abs of walk(join(ROOT, dir))) {
    const rel = abs.slice(ROOT.length).split("\\").join("/");
    if (SKIP.has(rel)) continue;
    const src = readFileSync(abs, "utf8");
    // **判据要求这个标记出现在注释行里**（行首、或 `*` / `//` 之后）。
    // 不这么写的话，本文件里那行 `const IGNORE_FILE_RE = …` 会让**门禁自己**整份
    // 免检——一个自我豁免的门禁比没有门禁更糟（它还会报绿）。
    if (IGNORE_FILE_RE.test(src)) {
      ignored.push(`${rel}:0`);
      continue;
    }

    const scanned = commentBlocks(src);
    // **解析失败必须是红的，不能是静默的。** 未闭合的块注释意味着从那一行到文件尾
    // 全部脱离校验——第一版把这种情况直接丢掉，失效时和通过长得一模一样。
    if (scanned.unterminated !== null) {
      errors.push(
        `${rel}:${scanned.unterminated} 有一个块注释一直到文件尾都没闭合，`
        + `从那一行往下的内容全部没有被校验——先把它闭合，或者来改 commentBlocks() 的扫描判据`,
      );
    }
    // ── 规则 C ──────────────────────────────────────────────────────────
    // **在合并/豁免切分之前跑**：它查的是注释的**结构**，而豁免标记是按行首装饰
    // 切段的——结构断了，切段本身就不可信，那时再问「这一段豁免没有」是本末倒置。
    for (const block of scanned.blocks) {
      for (const bad of topLevelLinesInJsdoc(block)) {
        errors.push(
          `${rel}:${bad.line} 块注释里有一行顶格起始（少了 \` * \` 前导）：${bad.text.slice(0, 40)}`
          + `——插入订正时压掉前导是本仓踩过的形态，而 tsc 与规则 A/B 都看不见它`,
        );
      }
    }

    for (const wholeBlock of mergeAdjacent(scanned.blocks)) {
      // **逐段豁免**：标记只放行它所在的那一段（到下一个空注释行为止），
      // 同一块注释里其余的段照常校验。
      const { runs, exemptRuns, markers } = splitByIgnore(wholeBlock);
      for (let n = 0; n < markers; n++) ignored.push(`${rel}:${wholeBlock.line}`);
      // **豁免掉的裁定计数逐处记名**（规则 F 的配套道具，不是统计）：
      // 用掉一次豁免之后那一段里放行了什么，本来没有任何东西看得见。
      for (const ex of exemptRuns) {
        if (flatten(ex.text).match(COUNTED_RULING_RE)) countedRulingExempt.push(`${rel}:${ex.line}`);
      }
      for (const block of runs) {
      const flat = flatten(block.text);
      // ── 规则 A ──────────────────────────────────────────────────────────
      for (const m of block.text.matchAll(PATH_RE)) {
        const target = m[1];
        const lineNo = m[2] === undefined ? null : Number(m[2]);
        const where = `${rel}:${block.line}`;
        if (!existsSync(join(ROOT, target))) {
          errors.push(`${where} 指向的 ${target} 不存在`);
          continue;
        }
        checked++;
        if (lineNo === null) {
          // 名字锚（可选）：`path「某某」`。在**压平后**的文本上找，见 flatten()。
          // **同一段话里对同一个文件的每一个锚都要校验**，不是只查第一个。
          const claims = CLAIM_MARKERS.some((k) => block.text.includes(k));
          for (const anchor of nameAnchorsAfter(flat, target)) {
            if (!anchorMatches(target, anchor, claims)) {
              errors.push(`${where} 指向 ${target}「${anchor}」，但那段文字不在那个文件里`);
            }
          }
          continue;
        }
        const lines = linesOf(target);
        if (lineNo < 1 || lineNo > lines.length) {
          errors.push(`${where} 指向 ${target}:${lineNo}，而那个文件只有 ${lines.length} 行`);
          continue;
        }
        if (!/\.test\.ts$/.test(target)) continue;
        const from = Math.max(0, lineNo - 1 - WINDOW);
        const to = Math.min(lines.length, lineNo + WINDOW);
        const window = lines.slice(from, to).join("\n");
        if (!TEST_ANCHORS.some((a) => window.includes(a))) {
          errors.push(
            `${where} 指向 ${target}:${lineNo}，但那一行上下 ${WINDOW} 行里没有任何用例声明`
            + `（it/test/describe/expect）——行号大概率已经漂了`,
          );
        }
      }

      // ── 规则 D ──────────────────────────────────────────────────────────
      // **在压平后的文本上找**：行号写法常被折行（「……在\n * 394 行」）。
      // **先把所有带路径的引用挖掉**，剩下的才是散文里的裸行号——不挖的话
      // `file.ts:123 那一行` 这种合法写法会被误伤。
      const withoutPaths = flat.replace(PATH_RE, " ");
      for (const m of withoutPaths.matchAll(PROSE_LINENO_RE)) {
        errors.push(
          `${rel}:${block.line} 散文里写了不带路径的绝对行号「${m[0].trim()}」。`
          + `那种行号没有任何东西在验它，改动一次就静静地变假（本仓实测过一次「出生即过期」）`
          + `——改成名字锚，或者写成 路径:行号 交给规则 A 去验`,
        );
      }

      // ── 规则 E ──────────────────────────────────────────────────────────
      // **必须排在规则 B 之前**：规则 B 那行 `continue` 会把「同段里没有断言性措辞」
      // 的段整段跳过，而门禁序号最常出现在纯陈述句里——写在它后面等于大半个仓不扫。
      // **同一段里同一个字面量出现多次时，逐条各指各的行**——见 `lineOfHit()` 的 `nth`。
      const seenLit = new Map();
      const nthOf = (lit) => {
        const n = seenLit.get(lit) ?? 0;
        seenLit.set(lit, n + 1);
        return n;
      };
      for (const m of flat.matchAll(GATE_ORDINAL_RE)) {
        const lit = m[0].trim();
        errors.push(
          `${rel}:${lineOfHit(block, lit, nthOf(lit))} 注释里写了门禁序号「${lit}」。`
          + `CI 里增删或重排一步，全仓所有序号一次性变假，而脚本名不会`
          + `——改写成「\`scripts/某个脚本.mjs\` 这道门禁」那种写法（脚本名存不存在由规则 A 当场校验）。`
          + `⚠️ 改成「写对的那个序号」一样红：判据禁的是绝对序号本身。`
          // **这句是复评逼出来的**：判据的 `CI 的第 N 道` 那一支会打红
          // 「CI 的第 N 道保险」这类**本来就正当**的句子（`道` 后面跟的不是「门禁」，
          // 只是前面挨着 CI 就被认了），而报文原来只给「改写成脚本名」和
          // 「改成写对的序号一样红」两条路——撞上的人只剩「把一句正确的话改坏」。
          // **报文把人引进坑，正是这道规则自己用来推翻需求书 `(?!\s*防线)` 的那一族缺陷。**
          // 逐字的那个例子在 `tests/unit/check-comment-refs.test.ts`
          // 「规则 E 的假红有正当出路：报文必须给出段级豁免」那一格里，不写在这儿——
          // 写在这儿这条规则会当场打中它自己。
          + `⚠️ 这一句本来就不是在说门禁（例如「CI 的第二道保险」）？`
          + `那就给那一段加 ${IGNORE_MARKER} 并在同一段里写明它不是门禁序号`
          + `——豁免会被逐处报出来、由元测试钉成手写清单，不会无声长大`,
        );
      }

      // ── 规则 F ──────────────────────────────────────────────────────────
      for (const m of flat.matchAll(COUNTED_RULING_RE)) {
        const lit = m[0].trim();
        errors.push(
          `${rel}:${lineOfHit(block, lit, nthOf(lit))} 注释里写了一个没人能核的裁定计数「${lit}」。`
          + `本仓已有的裁定是「要么列出来，要么把计数删掉」，本期一律把计数删掉`
          + `——改写成不带计数的说法（「本仓反复裁过的同一形态」）。`
          + `确实要逐字引用上一版原文时，给那一段加 ${IGNORE_MARKER} 并在同一段里写明`
          + `「这里的计数是被引用的对象」，那份豁免会被逐处报出来、由元测试钉成手写清单`,
        );
      }

      // ── 规则 B ──────────────────────────────────────────────────────────
      if (!CLAIM_MARKERS.some((k) => block.text.includes(k))) continue;
      for (const m of block.text.matchAll(TEST_FILE_RE)) {
        claimChecked++;
        if (m[2]) continue;                       // 已经带了行号
        if (nameAnchorsAfter(flat, m[1]).length > 0) continue;       // 带了名字锚
        errors.push(
          `${rel}:${block.line} 这段注释写了「${CLAIM_MARKERS.find((k) => block.text.includes(k))}」`
          + `却只给了裸文件名 ${m[1]}。指向必须写成 ${m[1]}:行号 或 ${m[1]}「用例名」`
          + `——逼你去把它找出来，正是这道门禁的全部作用。`
          // ⚠️ **这第二条出路是复评逼出来的，别再删掉**：命中是**按整段**算的
          //（那条口径由 `tests/unit/check-comment-refs.test.ts` 的
          // 「断言性措辞按整段连坐」一格钉着），于是一句纯描述性的
          // 「本模块只负责 X」会连坐同一段里一条纯描述性的指向。
          // 报文原来只给「去找出行号或用例名」一条路，撞上的人于是**去给一句描述句
          // 硬安一个锚**——而硬安出来的锚指的往往不是它在说的那件事。
          // **P3e Task 15A 那处假锚就是照着上一版这句报文做出来的**：
          // 报文说「把它找出来」，人就找了一条看起来像的用例名安上去，机器全绿而话是假的。
          // 报文是唯一会被看见的护栏，它给一条路，人就走那一条。
          + `⚠️ 触发它的那句话本来就不是在声称覆盖（「本模块只负责 X」这类描述句、`
          + `被同一段里的断言性措辞连坐）？**那就改那句描述，不要给它硬安一个锚**`
          + `——安上去的锚必须真的是「这句话由那一格守着」，`
          + `否则你只是把一条假指向换成了一条更难发现的假指向`,
        );
      }
      }
    }
  }
}

if (errors.length) {
  for (const e of errors) console.error(`[check-comment-refs] ❌ ${e}`);
  process.exit(1);
}
console.log(
  `[check-comment-refs] ✅ ${checked} 处注释里的仓内路径引用全部解析得开，`
  + `其中 ${claimChecked} 处带断言性措辞的测试引用都给出了行号或用例名；`
  + `${ignored.length} 段注释用了 ${IGNORE_MARKER} 豁免`,
);
if (process.env.COMMENT_REFS_LIST_IGNORED === "1") {
  for (const w of ignored) console.log(`[check-comment-refs] ignored ${w}`);
  for (const w of countedRulingExempt) console.log(`[check-comment-refs] counted-ruling-exempt ${w}`);
}
