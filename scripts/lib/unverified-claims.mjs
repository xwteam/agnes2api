/*
 * 「未核实的事不许被说成已核实」这条红线的**两张表**：key 白名单 × 软化词表（P3e Task 7）。
 *
 * ── 为什么这两张表住在这里，而不是各抄一份 ────────────────────────────────────
 * 它们有**三个消费者**，而三者问的是同一个问题：
 * · `scripts/check-i18n.mjs` 的规则⑨ —— CI 里那道 i18n 门禁，扫真字典；
 * · `tests/unit/i18n-dict.test.ts` 的「未核实的事不许被说成已核实（白名单 × 词表的交集）」
 *   —— 同一批 key 的**第二份扫描实现**（跑在 `pnpm test` 里）；
 * · `tests/unit/check-i18n.test.ts` 的
 *   「⑨ 反向自检：白名单非空、词表非空、且白名单里每个 key 都真的在字典里」
 *   —— 这两张表**自己**的反向自检（表空转时它变红）。
 * 抄三份的话，反向自检守的是它自己那一份副本：真扫描那份被改坏、或者白名单里的 key
 * 被改了个名字，它照样绿——本仓对这种形态的裁定写在 `scripts/lib/strip-comments.mjs`
 * 文件头（P3e Task 1 收编抠注释器时的同一条）：**两份不一致时，瞎掉的那一份才是报绿的那一份。**
 *
 * ⚠️ **共用的只是「表」，不是「扫描」。** 上面前两个消费者各写各的循环，
 * 其中一份写错时另一份会不同意；这里只保证两份问的是同一批 key、同一批词。
 *
 * ⚠️ **判据是白名单 × 词表的交集，不是全字典扫。** 词表里的「安全 / 够用 / 没问题」
 * 在别的命名空间里是完全正当的用词，全字典扫会立刻制造第二个「警报淹掉信号」现场
 *（这个仓刚刚才把 396 条噪音降到 0）。
 *
 * ⚠️ **边界：它证明的只是「没有人把未核实的事说成已核实」，不证明译文准确。**
 * 「这一档在 Worker 上跑得完」这种不含表内词的软化说法它抓不住，那一档留给评审。
 */

