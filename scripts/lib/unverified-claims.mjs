/**
 * 一个词在一段文案里算不算命中。**两份扫描各写各的循环，但判据必须是这一条。**
 *
 * ⚠️⚠️ **纯 ASCII 的词按词边界匹配，非 ASCII 的词按子串匹配 —— 这条不对称是实测逼出来的。**
 * 上一版两边都用裸 `includes`，于是英文 `defined` / `refined` 里的 `fine` 当场算命中，
 * 一句纯技术描述被门禁点名。CJK 没有词边界这回事（`問題な` 本来就是取词干、
 * 靠的就是子串），所以这条只对 ASCII 词生效。
 * 这一档由 `tests/unit/check-i18n.test.ts` 的
 * 「⑨ 反向控制：英文 defined 里的 fine 不许被当成软化词」钉着。
 *
 * ⚠️ **这个函数是给「怎么算命中」这条口径当真源的，不是把两份扫描合成一份**：
 * 两份扫描仍各写各的循环（谁扫哪些 key、报文怎么写、失败怎么表达都不同），
 * 共用的只是「表 + 这一条命中口径」。理由与文件头那段逐字同源。
 */
export function unverifiedHit(value, word) {
  const s = String(value);
  if (!/^[\x20-\x7E]+$/.test(word)) return s.toLowerCase().includes(word.toLowerCase());
  const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(String.raw`\b${escaped}\b`, "i").test(s);
}
