//「(e) 同一行上的空串字面量不许把后面那个 key 吃掉」那一格钉着。
const NSALT = [...NS].join("|");
const KEYLIKE = new RegExp(`["'](${NSALT})\\.[A-Za-z0-9_.]+["']`, "g");
// 模板拼键的**前缀**：`` `set.field.${path}` `` ⇒ `set.field.`。**取整段前缀，不取命名空间**：
// 放宽到 `set.` 会把 `set.card.*` 一并喂活，而那正是要处置的那一族。
//
// ⚠️⚠️ **「首段是不是字典命名空间」回答不了「这个模板在不在拼 i18n key」**——这是 P3e Task 3
// 复评实测出来的（L1）：`admin-ui/js/pure/settings.mjs` 里 `` `registrar.${channel}.baseUrl` ``
// 是一条**配置路径**，字典一旦新增 `registrar.*` 命名空间，它立刻进前缀表，把那一族里的
// 真死 key **静默喂活**。危害档位不是「多一条前缀」：第 ④ 条今天是硬错，
// 而被喂活的 key 根本不会出现在那份清单里 ⇒ **漏报，而漏报的表现是「什么事都没有」。**
// ⇒ 判据收窄成「**整条模板就是一个 key**」：`${…}` 一闭合模板就结束（`` `set.field.${path}` ``），
// 后面还跟着别的东西（`` `registrar.${channel}.baseUrl` ``）就不是拼键。
// ⇒ 而「首段是字典命名空间、但形状对不上」这一档**当场吵**，不许当成拼键也不许当没看见：
// 那正是分不清的那一档，静默选任何一边都会错，而错向「当成拼键」是喂活真死 key。
// 这两半由 `tests/unit/check-i18n.test.ts` 的
// 「拼键前缀：插值之后还跟着别的东西 ⇒ 分不清就吵，不许静默当成拼键」
// 那一格钉着，那一格自带反向控制：同一条模板在字典没有那个命名空间时**必须静默**
//（今天的真仓就是这一格，少了它「一律吵」也能让它绿）。
const TPL_PREFIX = /`([A-Za-z0-9_.]*\.)\$\{/g;
// 「整条模板就是一个 key」的形状。插值体里不许再出现花括号或反引号——嵌套模板 / 对象字面量
// 那几种同样是分不清的那一档，`test()` 落空之后走上面那条吵的路。**必须是粘性（`y`）的**：
// 它要回答的是「`TPL_PREFIX` 命中的**那一处**是不是这个形状」，不是「全文有没有这个形状」。
const TPL_WHOLE_KEY = /`[A-Za-z0-9_.]*\.\$\{[^`{}]*\}`/y;
// 内联 `<script>` / `<style>`：本门禁抠 HTML 只认 `<!-- -->`，那一段里的 JS/CSS 注释看不见。
const HTML_INLINE = /<(script|style)\b[^>]*>([\s\S]*?)<\/\1>/gi;

const directlyUsed = new Set();
const tplPrefixes = new Set();
for (const p of walk(join(ROOT, "admin-ui"))) {
  // 字典自己是定义处，扫它等于**每个 key 都自证被引用** ⇒ 第 ④ 条恒绿、判据整个作废。
  // 旧判据没跳它，因为旧判据只认 `t("…"` 与 `data-i18n=`，字典里都没有。
  if (p === DICT_FILE) continue;
  const raw = readFileSync(p, "utf8");
  const src = stripped(p, raw);
  // **HTML 里出现内联脚本 / 样式**⇒ 认不出就吵，不许静静地放行：那一段的注释语法是
  // JS/CSS 的，`stripHtmlComments` 看不见，被注释掉的 `data-i18n=` 会当成真引用混进来。
  // 今天 `admin-ui/index.html` 的两个 `<script>` 都只有 `src=`、零内联内容。
  //
  // ⚠️ **扫的是抠完注释的 `src`，不是 `raw`**：扫 `raw` 的话，一段**被 HTML 注释掉的**
  // 内联 `<script>` 会把这道门禁打成假红，而报文还劝人「把它挪进外链文件」——
  // 那段脚本本来就是死的，挪它是一件没有意义的活。这条由
  // `tests/unit/check-i18n.test.ts` 的「被 HTML 注释掉的内联 <script> 不算内联内容（否则门禁假红）」
  // 与它上面那条反向控制（真内联仍必须红）两格一起钉着。
  if (p.endsWith(".html")) {
    for (const m of src.matchAll(HTML_INLINE)) {
      if (m[2].trim() !== "") {
        errors.push(
          `${p.slice(ROOT.length)} 里有内联 <${m[1]}>：本门禁抠 HTML 只认 \`<!-- -->\`，`
          + "那一段里的 JS/CSS 注释看不见 ⇒ 被注释掉的引用会被当成真引用。"
          + "请把它挪进外链文件，或者去 scripts/lib/strip-comments.mjs 的 stripHtmlComments 扩判据",
        );
      }
    }
  }
  // m[0] 含首尾引号，去掉两端即为 key 本身；前缀已由正则锚死，这里不再回头判断。
  for (const m of src.matchAll(KEYLIKE)) directlyUsed.add(m[0].slice(1, -1));
  for (const m of src.matchAll(TPL_PREFIX)) {
    // 首段不是字典命名空间 ⇒ 与 i18n 无关的模板（拼路径、拼字段名），不进表也不吵。
    if (!NS.has(m[1].split(".")[0])) continue;
    TPL_WHOLE_KEY.lastIndex = m.index;
    if (!TPL_WHOLE_KEY.test(src)) {
      errors.push(
        `${p.slice(ROOT.length)} 里的模板 \`${m[1]}\${…}\` 以字典命名空间「${m[1].split(".")[0]}」开头，`
        + "但整条模板不止一个 key（`${…}` 之后还有别的东西）⇒ 分不清它是在拼 i18n key 还是在拼"
        + "配置路径 / 字段名。**分不清就吵，不许当成拼键**：当成拼键会把这个前缀底下**所有**"
        + "key 一并喂活，其中的真死 key 从此永远看不见。请把 key 拼成整条模板"
        + "（`` `set.field.${path}` `` 那种形态），或者改用一个不以字典命名空间开头的前缀",
      );
      continue;
    }
    tplPrefixes.add(m[1]);
  }
}

// ⚠️ **这里曾经有一道「只扫到 < 15 个引用就报错」的门槛，P3e Task 3 复评之后删掉了，别加回来。**
// 删它的理由不是「多余」，是**它论证自己的那段话已经不成立、而它本身有 97% 的死区**：
// · 那段话说它与 `tests/unit/i18n-dict.test.ts`「admin-ui 里引用的每个 key 都在字典里」
//   是同一个量的两份实现、必须同边界，否则会在「恰好等于 15」的边界上永久一绿一红。
//   实测两侧量的**已经不是同一个量**（那份测试仍用旧的两条窄正则、且不抠注释、也不扫
//   `index.html`），`=== 15` 两侧都不可达 ⇒ 那条对齐论证是空转的。
// · 换判据之后真实引用数是 ~496，判据可以瞎掉 97% 而这道门槛仍然一声不吭。
// **一条 97% 走不到的门槛与「一个不会自己红的清单」是同一族：那不是守卫，是待办。**
// 真正分辨「认对了」与「瞎了」的是 `tests/unit/check-i18n.test.ts` 里
//「(a)(b) elI18n(%s…) 里拼错的 key 被抓住（%s 形态）：exit 1」那两格**正向探针**
// 与它们各自的反向控制——瞎掉的判据什么都不吵，只有正向探针问得出话。
for (const k of [...directlyUsed].sort()) if (!(k in I18N)) errors.push(`引用了字典里没有的 key: ${k}`);

// **三个分桶是字典 key 的一个划分**：三个数加起来恒等于字典 key 总数。
// ⚠️ 「直接引用」数的是**字典里被直接引用的 key**，不是 `directlyUsed.size`——后者含
// 「字典里没有的 key」，加起来会超出总数，而那个和正是第 ④ 条那条硬错的观测量。
// ⚠️⚠️ **「拼键覆盖」这一桶等于「永久豁免死 key 检查」，读这个数之前先读这一段。**
// 落进这一桶的 key，静态判据永远看不出它到底有没有人用——它只知道「有一条模板可能拼出它」。
// 今天这一桶的构成是实测出来的，**写成事实而不是写成一个会漂的数**：
// · 覆盖**全部**来自 `set.field.`（`fieldLabelKey()` 那一族）；
// · `set.err.` 也在前缀表里，但它底下的 key **条条也被直接引用** ⇒ 它对这一桶的贡献是零，
//   只在横幅的「拼键前缀」那一行露面。别把「前缀表里有两条」读成「两族都被覆盖着」。
// ⇒ 也就是说：`set.field.*` 里没被直接引用的那一批，**第 ④ 条那条硬错看不见它们**——
//   P3e Task 4 那轮「处置真 0 命中 key」的输入里也没有它们。要处置得另找路
//   （比如把 `fieldLabelKey()` 的取值域枚举出来对账）。**这一桶不为零就等于有豁免在生效。**
const coveredByPrefix = Object.keys(I18N).filter(
  (k) => !directlyUsed.has(k) && [...tplPrefixes].some((p) => k.startsWith(p)),
);
const unreferenced = Object.keys(I18N).filter(
  (k) => !directlyUsed.has(k) && !coveredByPrefix.includes(k),
);
const directlyReferenced = Object.keys(I18N).filter((k) => directlyUsed.has(k));

// **分桶横幅在这里就打，而且不管后面红不红都打。**
// 放到最后的成功横幅里的话，门禁一旦 exit 1，三个分桶就看不见了——而
// 第 ④ 条已经是硬错（P3e Task 4），正需要它在**红着的时候**也能读出来。
console.log(
  `[check-i18n] 引用判据：直接引用 ${directlyReferenced.length} / 拼键覆盖 ${coveredByPrefix.length}`
  + ` / 未被引用 ${unreferenced.length}；字典共 ${Object.keys(I18N).length} 个 key`,
);
console.log(`[check-i18n] 拼键前缀: ${fmtList([...tplPrefixes].sort())}`);
console.log(`[check-i18n] 未被引用: ${fmtList(unreferenced)}`);

// ② 每个 key 都有全部 5 种语言且非空；③ 没有多余语言码
for (const [k, row] of Object.entries(I18N)) {
  for (const lang of LANGS) {
    const v = row[lang];
    if (typeof v !== "string" || v.trim() === "") errors.push(`${k} 缺 ${lang}`);
  }
  for (const lang of Object.keys(row)) {
    if (!LANGS.includes(lang)) errors.push(`${k} 有多余的语言码 ${lang}（拼错的语言码永远取不到）`);
  }
}

// ④ 字典里没被引用的 key ⇒ **错误，不是警告**（P3e Task 4）。
//
// ⚠️ 这条在 P3e 之前是 `console.warn`，`errors` 不收它 ⇒ **它永远不会 exit 1**。
// 当时的理由是「动态拼接的 key 抓不到，报错会误伤」，那条理由随 Task 3 一起失效：
// **模板拼键现在由下面那张前缀表认得出来**，而那张表与实扫做**双向**相等比较
//（见 `EXPECTED_TPL_PREFIXES`）⇒「未被引用」这个集合第一次变得可信。
// ⚠️ **这里刻意不写「今天全仓有几处模板拼键」**：那个数被数过好几轮、每一轮的答案都不同
//（同一条 `TPL_PREFIX` 正则在「抠不抠注释」「跳不跳字典文件」「算不算首段不是命名空间的那些」
// 三处各自分叉），而它对这条判据毫无作用——要知道今天扫出哪几条前缀，读横幅第二行。
// ⚠️ **`+` 拼键仍然不被支持**：它是第 ① 条上面那段边界里登记的三种漏报形态之一，
// 升成硬错之后它的后果就是下面那段 ⚠️ 说的「打红一个正在用的 key」。
// **一个不会自己红的清单不是守卫，是待办**——那是本仓对这种东西的裁定。
//「未被引用」读的是上面那个分桶（已扣掉被拼键前缀覆盖的那一批）。
//
// ⚠️ **升成硬错之后，第 ① 条上面那段「边界」里登记的三种漏报形态就是打红**：
// 真写出 `"a." + b` / 反引号里的纯 key / HTML 里不带引号的属性值，红的是一个**正在用**
// 的 key，而顺着报文去「清理未被引用的 key」删掉的就是活着的界面文案。
// 真出现时请把它改写成判据认得的形态，或者去扩第 ① 条，**别顺手删 key**。
// 这一条由 `tests/unit/check-i18n.test.ts` 的
//「④ 字典里谁都不引用的 key ⇒ 当场红」与它的反向控制
//「④ 反向控制：模板拼键 + 同前缀 key ⇒ 不许红」两格一起钉着（**只做一半等于没做**：
// 单看前一格，「一律 exit 1」也能让它绿）。
for (const k of unreferenced) errors.push(`字典里有未被引用的 key: ${k}`);

// ⚠️⚠️ **处置指引必须写进报文本身，不能只写在上面那两段注释里**（P3e Task 4 复评 F2）。
// 复评实测：把 `set.card.upstreamNote` 唯一那处引用改写成 `"set" + ".card.upstreamNote"`
//（登记在案的三种漏报形态之一）⇒ 门禁 exit 1，而运维在 CI 里看到的**全部**输出就是
// 上面那一行「字典里有未被引用的 key: <一个正在用的 key>」。**读 CI 输出的人不会回头
// 读源码注释**，顺着那一行去「清理未被引用的 key」删掉的就是活着的界面文案。
// 同一批新增的「模板拼键前缀变了」那条报文把处置指引写进了报文本身，而危险得多的
// 这一条当时没有 —— 两条同批新增的硬错，指引给反了。
//
// ⚠️ **刻意每轮只打一条，不是每个 key 各附一份**：真出问题时这份清单可以是整整一族
//（第 ① 条上面 `/^[a-z]+$/` 那个筛子真筛掉一个前缀时，那个命名空间底下的 key 会整族
// 落进来），把同一段指引重复几十遍就变成了滚屏噪音——本仓那条「一个诚实标记出现得
// 太密就不再传递信息」说的正是这个。它跟在那一族点名**之后**打：读的人先看见是哪些 key，
// 再看见该拿它们怎么办。
// 这一条由 `tests/unit/check-i18n.test.ts` 的
//「④ 的硬错报文自带处置指引 —— 读 CI 输出的人不会回头读源码注释」与它的反向控制
//「④ 处置指引的反向控制：没有未被引用的 key 时不许出现」两格一起钉着
//（**只做一半等于没做**：单看前一格，「无条件打这一段」也能让它绿）。
if (unreferenced.length > 0) {
  errors.push(
    "上面这批「未被引用」里可能混着**正在用**的 key —— 第 ① 条有三种已知漏报形态："
    + "① 按 `+` 拼的 key；② 反引号里的纯 key 字面量；③ HTML 里不带引号的属性值。"
    + "**先去 admin-ui/ 下确认它真的一处引用都没有，再决定删不删，别顺手删 key**"
    + "（删错了面板上显示的是裸 key 串）。确实还在用就把那处引用改写成判据认得的形态"
    + "（单引号或双引号的字符串字面量），或者去 scripts/check-i18n.mjs 扩第 ① 条",
  );
}

// **拼键前缀钉成双向断言**（P3e Task 4，理由见上面 `EXPECTED_TPL_PREFIXES`）。
// 双向是必须的：只查「实扫 ⊆ 登记」的话，一张越写越长的表会静静地把
// 「这条前缀早就不存在了」变成一条永久豁免，而永久豁免正是第 ④ 条最怕的东西。
const gotTplPrefixes = [...tplPrefixes].sort();
if (gotTplPrefixes.join("|") !== [...EXPECTED_TPL_PREFIXES].sort().join("|")) {
  errors.push(
    `模板拼键前缀变了：登记的是 ${fmtList(EXPECTED_TPL_PREFIXES)}，实扫是 ${fmtList(gotTplPrefixes)}。`
    + "前缀写宽一格，那一族 key 就再也不会被报未被引用"
    + "（把 `set.field.` 放宽成 `set.`，覆盖范围就从那一族扩成整个 `set.*` 命名空间）"
    + "⇒ 改动是有意的就回 scripts/check-i18n.mjs 改 EXPECTED_TPL_PREFIXES，别只改源码",
  );
}

// ⑤ 插值 token 在 5 种语言里集合相同
for (const [k, row] of Object.entries(I18N)) {
  const sets = LANGS.map((l) => [...String(row[l] ?? "").matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(","));
  if (new Set(sets).size !== 1) errors.push(`${k} 的插值占位符在各语言间不一致: ${sets.join(" | ")}`);
}

// ⑥ 偏好词：`reg.*` 与 `keys.addMenu.auto*`，**外加与「两条通道平级」直接相关的那几个
// `set.*` 前缀**（含繁体变体）。
//
// ⚠️ **`keys.addMenu.auto*` 是复评追加的范围，原来只扫 `reg.*`**：P3c Task 4
// 新增的「添加 Key」下拉里，【自动注册】那两项占位文案（`keys.addMenu.autoGroup`
// / `autoMoemail` / `autoYyds`）与 `reg.*`（P2 注册机）
// 说的是同一类事——"这条通道有没有被暗示成比别的通道更好"——但原来的判据
// 只认命名空间前缀 `reg.`，这几个 key 完全不在扫描范围内，复评实测：给
// `keys.addMenu.autoMoemail` 塞一句「推荐使用」，**当时的八条断言全绿**。这条门禁
// 必须在 Task 6 真正给这两条通道接线、写更多面向运维的文案之前先扩到这里。
//
// ⚠️⚠️ **后三条前缀是 P3e Task 7 追加的**，起因同型、危害更大：用户那条硬约束是
// 「YYDS 与 MoeMail 严格同级，不替人选主备」，而两条通道**共用的那对凭据 key**
// （`set.field.channel.*`）与主 / 备两个选择器标签（`set.field.registrar.primary`
// / `fallback`）、注册机那张卡的标题（`set.card.registrar`）在这之前**全在门外**——
// 夹具实跑 EXIT=0。设置页正是运维**真的在做那个选择**的地方。
//
// ⚠️ **为什么不是整个 `set.*`（这条推理必须留着，删了下一个人会顺手扩宽）**：
// `set.*` 里有与通道无关、却**正当地**含着表内词的运维文案。**逐字的那一条是
// `set.field.agnesBaseUrl`：它的 ko 值是「업스트림 기본 URL」，`기본` 在这里是
// base URL 的「基」，与「默认通道」毫无关系**——放宽成整个 `set.` 就会当场打红它。
// ⚠️ **这里刻意只举这一条真的，不写「大量（超时、冷却、口令）」那种全称句**：
// 上一版就是那么写的，而本轮实测放宽成 `set.` 之后全字典**只命中上面那一条**，
// 超时 / 冷却 / 口令三族一条都没中 ⇒ 那句话当时就是假的，而「不许扩宽」这条推理
// 的全部载重都压在它身上。**一条真的反例胜过一句无人能核的全称句。**
// 扩太宽 = 这道今天零命中的干净门禁立刻要带一条豁免名册，
// 而本仓的裁定是「开豁免名册比没有规则更糟」。
