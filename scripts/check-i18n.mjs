const CJK = /[㐀-䶿一-鿿぀-ヿ가-힯]/;
const HAN = /[㐀-䶿一-鿿]/;
const HANGUL = /[가-힯]/;
for (const [k, row] of Object.entries(I18N)) {
  const en = String(row.en ?? "");
  if (CJK.test(en)) errors.push(`${k}/en 里出现了 CJK 字符，多半是整段没翻译: ${en}`);
  const zh = String(row["zh-CN"] ?? "");
  const ko = String(row.ko ?? "");
  if (HAN.test(zh) && !HANGUL.test(ko)) {
    errors.push(`${k}/ko 一个谚文都没有，而 zh-CN 是含汉字的句子，多半是整段没翻译: ${ko}`);
  }
}

