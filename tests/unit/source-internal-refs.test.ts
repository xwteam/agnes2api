/**
 * ── ⑧ 那一格抽得走本轴这三族 ────────────────────────────────────────────────
 *
 * `scripts/prepush.sh` 的 ⑧ 扫提交信息，而**提交信息推出去就改不动**。它的族定义
 * 一个字都不手抄，全靠当场抽；抽不走的族在提交信息上就是没人守，而那一格的失败模式
 * 恰恰是**少抽还照样绿**。⇒ 本组盯的是「这三族在本文件里的形态，⑧ 那边抽得走」。
 *
 * ⚠️ 抽取形态与 ⑧ 里那段 `awk` 逐字对应：`id:` / `source: expand("…")` / `flags:` /
 * `evidence: expand("…")` 各占一行、按族相邻。这里用**同一套形态**再抽一遍本文件，
 * 抽出来的必须与运行时那张 `FAMILIES` 逐字相等 —— 哪天有人把某一族的正则源改回
 * 模板串或加号拼接，运行时照常绿，而这一格当场红。
 */
describe("⑧ 抽得走：这三族在本文件里是单行可抽的形态，且证据串认得出自己", () => {
  type Extracted = { id: string; source: string; flags: string; evidence: string };

  /** 与 ⑧ 里那段 `awk` 同一套形态：逐行走，见到 `evidence: expand(…)` 就收一族。 */
  function extractMsgGateFamilies(text: string): Extracted[] {
    const out: Extracted[] = [];
    let id = "";
    let flags = "";
    let source: string | null = null;
    for (const line of text.split("\n")) {
      const mi = /^ +id: "(.*)",$/.exec(line);
      if (mi) { id = mi[1] as string; continue; }
      const ms = /^ +source: expand\("(.*)"\),$/.exec(line);
      if (ms) { source = ms[1] as string; continue; }
      const mf = /^ +flags: "(.*)",$/.exec(line);
      if (mf) { flags = mf[1] as string; continue; }
      const me = /^ +evidence: expand\("(.*)"\),$/.exec(line);
      if (me && source !== null) {
        out.push({ id, source: expand(source), flags, evidence: expand(me[1] as string) });
        source = null;
      }
    }
    return out;
  }

  it("🔴 名册双向查：带 `evidence` 的族 = `MSG_GATE_FAMILY_IDS`，一条不多一条不少", () => {
    expect(FAMILIES.filter((f) => f.evidence !== undefined).map((f) => f.id),
      "带证据串的族与那张名册对不上 —— 名册少一条 ⇒ ⑧ 少抽一族（而它会照样绿）；"
      + "名册多一条 ⇒ 那一族的证据串没写，⑧ 的四栏对齐自检会当场把这一格判成「判据坏了」")
      .toEqual([...MSG_GATE_FAMILY_IDS]);
    for (const id of MSG_GATE_FAMILY_IDS) {
      expect(FAMILIES.map((f) => f.id), `名册上的族「${id}」不在族表里`).toContain(id);
    }
  });

  it("🔴 每一族登记的证据串，展开之后必须被自己那条正则抓住", () => {
    for (const f of FAMILIES) {
      if (f.evidence === undefined) continue;
      // `reOf()` 现造，理由写在它头上：带 `g` 的正则身上那个 `lastIndex` 是共享可变状态。
      expect(reOf(f).test(f.evidence),
        `族「${f.id}」的证据串「${f.evidence}」没被它自己那条正则抓住 —— `
        + "⑧ 那边会红在「判据坏了」上，而不是红在提交信息上").toBe(true);
    }
  });

  it("🔴 抽取形态对得上：拿 ⑧ 那套形态抽本文件，抽出来的与运行时那张族表逐字相等", () => {
    const got = extractMsgGateFamilies(realFile(SELF_PATH));
    const want = FAMILIES.filter((f) => f.evidence !== undefined)
      .map((f) => ({ id: f.id, source: f.source, flags: f.flags, evidence: f.evidence as string }));
    expect(got, "抽出来的与运行时对不上 —— 多半是某一族的正则源被改回了模板串 / 数组 / "
      + "加号拼接。运行时照样绿，而 ⑧ 那边从此少抽一族").toEqual(want);
  });

  it("🔴 该红时红：把某一族改回模板串 ⇒ 这一套形态当场少抽一族", () => {
    const mutated = realFile(SELF_PATH).replace(/^( +source: )expand\("(.*)"\),$/m, "$1`$2`,");
    expect(extractMsgGateFamilies(mutated).length,
      "把一族的正则源改回模板串之后居然还抽得到同样多族 —— 这一格验的是空气")
      .toBe(MSG_GATE_FAMILY_IDS.length - 1);
  });
});

