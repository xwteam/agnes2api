/** 工作账本那个目录名。它被 `.gitignore` 排除、不随仓库推送 ⇒ 底下的东西按定义不在仓里。 */
const LEDGER_DIR = ".superpowers";

/**
 * 引用形态：一个 `.md` 结尾的名字，两侧都不许再跟词字符 / 点号 / 连字号。
 * 前置边界把点号与连字号也排掉，是为了不把一个带内点的名字从中间切开、
 * 只取到它的后半截（那会凭空造出一个仓里没有的名字）。
 */
const MD_REF_SOURCE = "(?<![\\w.\\-])([A-Za-z0-9_][\\w.\\-]*\\.md)(?![\\w\\-])";

type DocRef = {
  readonly path: string;
  readonly line: number;
  readonly name: string;
  readonly context: string;
};

/**
 * 射程里全部 `.md` 引用。
 *
 * `carveOut` 为真时（默认），**紧挨在工作账本目录底下**的引用一律跳过：
 * 那个目录被 `.gitignore` 排除，底下的文件按定义永远不在 `git ls-files` 里
 * ⇒ 不跳过它就是一条**永久假红**。这一档已经由 `tests/unit/repo-front-door.test.ts`
 * 的 (e) 组另判（那一组要的是「同一份文件里写出溯源限定」，与本条要的
 * 「文件必须存在」是两个互相矛盾的合规条件，同一处不许被两条规则各判一次）。
 * ⚠️ 判的是**紧挨着的那一段路径前缀**，不是「这一行里出现过那个目录名」——
 * 后者会把同一行里别的引用一起放走。
 */
function mdRefs(read: FileReader, files: readonly string[] = SCOPE, carveOut = true): DocRef[] {
  const out: DocRef[] = [];
  const ledgerTail = new RegExp(`${LEDGER_DIR.replace(".", "\\.")}[\\w.\\-/]*$`);
  for (const path of files) {
    const lines = read(path).split("\n");
    for (const [i, line] of lines.entries()) {
      // 正则每一处现造，理由与 `reOf()` 头上那段逐字相同。
      const re = new RegExp(MD_REF_SOURCE, "g");
      for (const m of line.matchAll(re)) {
        if (carveOut && ledgerTail.test(line.slice(0, m.index ?? 0))) continue;
        out.push({ path, line: i + 1, name: m[1] as string, context: line.trim().slice(0, 70) });
      }
    }
  }
  return out;
}

