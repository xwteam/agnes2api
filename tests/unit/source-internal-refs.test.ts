const ALLOWED_MD_NAMES: readonly string[] = FIXTURE_MD_ALLOWLIST.map((e) => e.name);

/** 本判据自己的路径。白名单的第三向查要把它排掉，理由写在那张表上。 */
const SELF_PATH = "tests/unit/source-internal-refs.test.ts";

/** 解析不开、又不在白名单里的引用 —— 正向那一格读的就是它。 */
function danglingDocRefs(read: FileReader, allow: readonly string[] = ALLOWED_MD_NAMES): DocRef[] {
  return mdRefs(read).filter((r) => !REPO_BASENAMES.has(r.name) && !allow.includes(r.name));
}

/** 白名单里能解析到实体的条目 —— 名册过期，反向那一格读的就是它。 */
function staleAllowlist(allow: readonly string[] = ALLOWED_MD_NAMES): string[] {
  return allow.filter((n) => REPO_BASENAMES.has(n));
}

/** 白名单里在本判据之外一处引用都没有的条目 —— 空转，第三向读的就是它。 */
function idleAllowlist(read: FileReader, allow: readonly string[] = ALLOWED_MD_NAMES): string[] {
  const live = new Set(
    mdRefs(read, SCOPE.filter((p) => p !== SELF_PATH))
      .filter((r) => !REPO_BASENAMES.has(r.name))
      .map((r) => r.name),
  );
  return allow.filter((n) => !live.has(n));
}

