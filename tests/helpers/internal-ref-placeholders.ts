/**
 * ── 那几个占位符的**唯一真源**：值在这里拼出来，谁要用谁 import ────────────────
 *
 * 这几个常量原先躺在 `tests/unit/source-internal-refs.test.ts` 里，搬出来只为一件事：
 * `scripts/prepush.sh` 里那段 `expand_placeholders` 是**第二份手抄件**，得有人拿真值
 * 与它逐字节比。比它的那一格写在 `tests/unit/prepush-guard.test.ts`
 * 的「🔴 两张展开表逐 token 比对：shell 那段展开与真源那张表逐字节相等」里。
 * ⚠️ **不能让它直接 import 那份判据**：那是一份 vitest 测试文件，被别人 import 之后
 * 整套用例会挂到 import 它的那份文件上，`scripts/prepush.sh` 那两行文件数 / 用例数
 * 当场对不上。⇒ 值放在 helper 里，两份判据各 import 一次，helper 自己不带任何用例。
 *
 * ⚠️ **本文件同样在源码轴的射程里**（它是跟踪文件，判据扫的就是全部跟踪文件）：
 * 下面两个常量必须**拼出来**，理由与它们原先那段注释逐字相同 ——
 * 原样写成字面量，就是往一份读者克隆就看得到的文件里写一处真串。
 */

/**
 * 大写字母那个区间的写法，**拼出来**。理由与探针串同一条：本文件在射程里，
 * 把它原样写成字面量就是自己命中「字母 + 连字号 + 字母」那一族。
 */
export const UPPER = "A" + "-" + "Z";

/**
 * 那个内部评审轮次的**三字母缩写**，同样**拼出来**，理由与 `UPPER` 逐字相同：
 * 本文件在射程里，而那一族认的就是它 —— 原样写成字面量再跟上一个标记，
 * 判据里「本文件自己零命中」那一格当场红在本文件上。
 */
export const ROUND = "A" + "DJ";

/**
 * 圈号那几段码位，拼成一个字符类的内容。
 * 三段加一个零号：`①`–`⑳`（U+2460–U+2473）、`㉑`–`㉟`（U+3251–U+325F）、
 * `㊱`–`㊿`（U+32B1–U+32BF），另收 `⓪`（U+24EA）。
 * ⚠️ **单靠圈号本身当不了判据**：上一轮清理前实测，全仓 2413 处圈号里只有 83 处是
 * 那册子的条号，其余 2330 处是前九轮拿 `①②③` 顶掉编号之后留下的分项标记。
 * ⇒ 圈号只能当**后缀标记**用，锚必须钉在上面那个缩写上。
 * ⚠️ 这一条**不必拼**：单独一串圈号身上没有任何一族的形状（锚在缩写上，缩写不在这里）。
 */
export const CIRCLED = "⓪①-⑳㉑-㉟㊱-㊿";

/**
 * ── 占位符：**让「拼出来」的那几个串重新变成一行可抽的字面量** ────────────────
 *
 * 上面几个常量为什么要拼出来，各自那段注释已经写清了：它们所在的文件在射程里，
 * 原样写成字面量就是自己命中自己。代价是**族表里那几条正则源成了模板串 / 数组 /
 * 加号拼接**，一行 `grep` 抽不走它们。
 *
 * 🔴 **而它们必须被抽走**：`scripts/prepush.sh` 的 ⑧ 扫的是**提交信息**，
 * 而提交信息一旦推出去就改不动（那一格自己的注释里记着一笔 254 处的已公开欠账）。
 * ⑧ 从文档轴那份判据当场抽族定义，可文档轴没有源码轴那几族 ⇒ 抽不走就等于没人守。
 * ⚠️ **出路不是让 ⑧ 手抄一份族定义**：手抄的会漂，而且漂了没人会发现（那是 ⑧ 自己
 * 文件头上逐字写着的立法理由）。出路是把这几条正则源写成**单行 + 占位符**：
 * 文件里躺着的是 `{大写区间}` 这种不成形状的写法，运行时才被 `expand()` 换回真值。
 *
 * 🔴 **但展开表本身仍然是两份**：`expand()` 一份、`expand_placeholders` 一份，
 * 而后者按定义没法 import 前者（它是 shell）。⇒ 那两份之间只能靠**一格逐 token 的
 * 字节比对**兜住，兜它的用例名写在本文件头上那段里。
 * ⚠️ **别再把这件事记在「正向自检」头上**：那一步实测兜不住（尤其那个缩写，
 * 它在正则源与证据串两边同时展开，一起漂了照样匹配）。逐条哪个兜得住、哪个兜不住，
 * 写在 `tests/unit/source-internal-refs.test.ts` 文件头第 ⑩ 条里。
 *
 * `{}` 那一条是**空串**：它不换出任何东西，只用来把一个证据串从中间掰开
 *（`P{}3c` 写在文件里不是一个阶段编号，展开之后才是）。理由与上面几个常量逐字相同。
 */
export const PLACEHOLDERS: ReadonlyArray<readonly [string, string]> = [
  ["{}", ""],
  ["{UPPER}", UPPER],
  ["{ROUND}", ROUND],
  ["{CIRCLED}", CIRCLED],
];

/** 把一条带占位符的单行串展开成真值。⑧ 那一格里有一段同口径的展开。 */
export function expand(s: string): string {
  let out = s;
  for (const [token, value] of PLACEHOLDERS) out = out.split(token).join(value);
  return out;
}
