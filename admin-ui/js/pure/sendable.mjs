/**
 * 管理口令的字符集判定。**前后端共用同一份定义**（后端那份是
 * `src/http/admin/auth.ts` 的 `SENDABLE` / `isSendable`），由
 * `tests/ui/sendable-parity.test.ts` 的**逐码位行为等价**断言钉着。
 *
 * ── 字符集是 `0x20–0x7E`，理由分三段，性质不同，别再混着说 ────────────────
 *
 * 上一版把这三段压成一句「浏览器发不出去的字符」，那句话对其中一段是**假的**，
 * 而它在八处以上被复述。危害不是安全洞（方向仍是 fail closed），是**对运维说了
 * 一句他一试就能证伪的话**——他在浏览器里试一下发现送得出去，然后认定网关在骗人。
 *
 * **(a) 码点 > U+00FF，以及 NUL / LF / CR —— 物理，发生在浏览器。**
 *   `new Headers().set()` 直接抛 `TypeError`（Fetch 规范：头值是 ByteString，
 *   码点 > 255 转不过去；NUL/LF/CR 过不了头值校验）。实测（node v24 的 undici，
 *   与浏览器同一套规范实现）：CJK / emoji / 零宽空格 / NUL / LF / CR 全部 **THROWS**。
 *   这种口令会装出一棵 200 但永远进不去的面板：用户看到「网络错误」，
 *   而服务端**连一条 login_failed 都没有**（请求压根没发出来）。
 *
 * **(b) 其余 C0 控制字符与 DEL（0x00–0x1F、0x7F）—— 物理，但发生在服务端解析器。**
 *   浏览器**送得出去**（实测 BEL 0x07 / ESC 0x1B / DEL 0x7F 全部 ACCEPTED），
 *   但 HTTP 解析器会拒。实测（裸 `http.createServer` + 原始 socket 塞单字节）：
 *   BEL / ESC / DEL 一律 **400 Bad Request**，handler 根本收不到这次请求。
 *   ⚠️ **workerd 侧没验**，如实标注：这是个双运行时项目，别把 Node 的实测当成两边的答案。
 *
 * **(c) `0x80–0xFF` 可打印字节（`é` `£` 不间断空格 …）—— 送得出去，也真的能用。
 *   排除它是我们的稳健性取舍，是口味，不是物理。**
 *   实测：浏览器侧 ACCEPTED；Node 解析器侧 **200 OK**，handler 收到的码点与发出的
 *   逐一对应（`0xE9` → U+00E9）；而 `process.env` 里 UTF-8 的 `é` 解出来同样是 U+00E9
 *   ⇒ 两者**逐码点相等**，`ADMIN_TOKEN="admin-token-café-0123456789"` 端到端能用。
 *   （实测同时订正了一处分组：**NEL 0x85 不被 Node 解析器拒**，200 OK 且如实交出
 *   U+0085 —— 它是 C1，结构上属于本段而不是 (b)。）
 *
 *   那为什么还是拦？两条，都写清楚：
 *     · **跨运行时编码口径不一致是真的**：环境变量按 UTF-8 解、HTTP 头值按 Latin-1 解，
 *       两边碰巧在 U+0080–U+00FF 这段对上是**实现细节**，不是规范承诺；
 *       **而 workerd 侧我们没验过**，双运行时项目里未验证的行为差异就是风险。
 *     · RFC 9110 已把 obs-text（0x80–0xFF）标为**弃用**，中间件/反代对它的处置各不相同。
 *   而非 ASCII 口令**不是一个有价值的形态**（它不比同长度的 ASCII 更强），是个坑。
 *
 * ── 与「空格」那条的区别（本轮评审刚裁过，写在这里免得下次又摇摆）─────────
 *
 * 空格 0x20 也曾被排除，理由是「怕复制粘贴出错」——那条**已经被裁掉并放行**了，
 * 因为：空格是**纯 ASCII，跨运行时零编码歧义**，而带空格的 passphrase
 * （`correct horse battery staple`）是**有价值的常见形态**，拒它纯属替运维做主。
 * `0x80–0xFF` 两条都不成立：有真实的编码歧义、又不是有价值的形态。
 * **判据不是「是不是口味」，而是「这个限制换来的稳健性值不值它挡掉的形态」。**
 * (c) 仍然是口味，只是这一次口味的收益 > 代价——所以它被**标成口味**保留，
 * 而不是被伪装成物理。
 *
 * 这个目录下的文件受三条硬规则约束，规则全文见 admin-ui/README.md。
 */

/**
 * 量词是 `*`：这条规则说的是「不含送不出去的字符」，**非空不是它的职责**
 *（后端归 `too_short`，前端归 `gate.empty`，两边各自的上游判断都先把空串接走了）。
 *
 * ⚠️ 上一版前端写 `+`、后端写 `*`，是一处刻意但**多余**的不对称：它让「两边一致」
 * 这句话必须带一个空串的例外，护栏也就只能做到「除了空串以外一致」。
 * 统一成 `*` 之后，等价关系对**全部输入**成立，`sendable-parity` 才能做无例外的
 * 逐码位行为断言。行为没有变化：`app.js` 里 `if (!key)` 仍然先接走空输入。
 */
const SENDABLE_RE = /^[\x20-\x7e]*$/;

/** 这个字符串能不能被客户端送出去、并被服务端解析器收下。 */
export function sendable(s) {
  return SENDABLE_RE.test(s);
}
