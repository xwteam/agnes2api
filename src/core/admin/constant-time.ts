/**
 * 常数时间比较：先比长度，再逐字节异或累加，**中途不提前 return**。
 *
 * 长度本身会泄漏（长度不同时立刻 false），这是标准取舍：被它比较的两侧都是随机串
 *（管理口令 ≥24 位、对外子 key 的摘要恒 64 位十六进制），泄漏长度不构成可利用的
 * 信息，而为了藏长度去做定长填充只会让实现更容易写错。
 *
 * ⚠️ **常数时间这个性质无法用单元测试证明，原因是它根本不在返回值里**：
 * 被测的性质是「**耗时**不随输入而变」，而测试只能断言返回值。把整个函数换成
 * `a === b`、或把循环体改成 `if (a[i] !== b[i]) return false`，**返回值逐点相同**，
 * 变的只是耗时——所以任何基于返回值的断言都区分不了它们（已实测：两条变异全套测试
 * 照样绿，两条变异都当场量过）。
 *
 * 那为什么不写计时断言？因为在 CI 上测不准：几十个字节的逐字节差异是纳秒量级，
 * 而 JIT 预热、GC、共享 runner 的调度噪声是毫秒量级，信噪比根本不够，写出来的
 * 只会是一条随机红绿的用例——那比没有更糟。
 *
 * 所以这一条**明确不由测试保证，而由评审保证**：评审时逐字核对下面的循环体里
 * 没有任何提前 return / break / 短路运算（`&&` `||` `?:`），出现就是回归。
 *
 * ── 它为什么住在 `src/core` 而不是 `src/http/admin/auth.ts` ──────────────────
 * 它原来是那个文件里的一个导出，而对外 API 密钥那条查表路径
 *（`src/core/admin/api-keys.ts` 的 `findByDigest`）需要**同一份**实现：
 * 摘要比对与口令比对是同一件事，各写一份的后果是其中一份迟早被"优化"成 `===`，
 * 而两份里被改的那一份没有任何自动化看得见（上面那段已经说明了为什么）。
 * `src/core` 不许 import `src/http`（分层），所以真源挪到这里，
 * `src/http/admin/auth.ts` **原样再导出一次**——它的既有调用方（契约测试）
 * 一直都是从那个模块拿它，为一次搬家去改那些调用点不值得。
 */
export function constantTimeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}
