import type { Mailbox } from "../core/registrar/types.js";

/**
 * `verifyCredentials()` 成功那一支的返回形状。
 *
 * **只有一格 `cleaned`，而且它是必填的。** 证明凭据这件事在有的实现上要先建一个
 * 东西出来（见 `MailProvider.verifyCredentials`），建出来的东西**必须删掉**；
 * 而「删失败了」是一件调用方**非说不可**的事——它占着这条通道的活跃邮箱名额，
 * 而那个名额是补池能不能继续工作的前提。做成可选字段（`cleaned?: boolean`）
 * 就等于允许一个实现**什么都不说**，而「什么都不说」在面板上会被渲染成「干净的」
 * ——那正是一句没人负责的假话。
 *
 * ⚠️ **`cleaned: true` 的含义是「确认删掉了」，不是「大概删掉了」。**
 * 压根没建东西的实现恒为 `true`（没有残留可言）；建了东西又没能确认删掉的，
 * 一律 `false`，**不许因为「多半删掉了」就报 `true`**。
 */
export interface CredentialProof {
  /** 这次证明凭据时建出来的东西有没有**确认**清理干净。没建过东西的实现恒为 `true`。 */
  readonly cleaned: boolean;
}

/**
 * 临时邮箱服务。两家实现的差异（列表接口带不带正文、用地址还是 id 定位）全部封在
 * 适配器内部，`mintOne` 对它们一视同仁。
 */
export interface MailProvider {
  readonly name: "yyds" | "moemail";
  /** 可用域名。Agnes 会按域名屏蔽一次性邮箱，调用方需要多个域名可轮换。 */
  listDomains(): Promise<string[]>;
  createMailbox(domain: string): Promise<Mailbox>;
  /** 轮询验证码。超时返回 null 而不抛错。 */
  pollCode(mailbox: Mailbox, timeoutMs: number): Promise<string | null>;
  /**
   * 用完即删。**返回值是「确认删掉了没有」**，不是「有没有抛错」：非 2xx 会正常
   * resolve，只看抛不抛错的调用方一律读成「删掉了」。
   * 失败只应记日志，不影响已拿到的结果——`mintOne` 因此**不看**这个返回值。
   */
  deleteMailbox(mailbox: Mailbox): Promise<boolean>;

  /**
   * **证明这把凭据今天真的能用。**
   *
   * ── 为什么这是一条 provider 级的能力，而不是面板里的一张表 ──────────────────
   *
   * 「谁在哪一步校验凭据」是一句关于**别人家服务今天行为**的断言：有的服务列域名
   * 那一步就查，有的要到建邮箱那一步才查。把它写成面板/handler 里的分支，就是把
   * 那句断言钉进本仓，上游改一次版它腐烂成假话，**而没有任何门禁看得见它腐烂**。
   * ⇒ 让每个适配器**自己**决定怎么证明，面板只问「验过了没、结果是什么」。
   * 腐烂的风险因此落在适配器里——那本来就是它该在的地方。
   *
   * ── 契约 ──────────────────────────────────────────────────────────────────
   *
   * · **resolve** ⇒ 上游接受了这把凭据。返回值里说清残留清理干净了没有。
   * · **抛错** ⇒ 结论由错误身上挂的状态码决定（`httpFailStatus`）：
   *   `401`/`403` = 凭据被拒；`429` = 上游在限流，这一次什么都没证明出来；
   *   其余（含没有状态码）= 上游抖动/连不上，同样什么都没证明出来。
   *   **实现只管把真实的状态码原样挂上去**（用 `httpFail`），分档不在这里做。
   *
   * ⚠️ **实现里不许把「限流 / 连不上」翻译成「凭据无效」。** 这三者的处置完全相反，
   * 而运维手上只有面板那一句话。做法就是别 catch：让 `httpFail` 那个状态码穿出去。
   *
   * ⚠️ **代价明写**：有的实现要建一个临时邮箱再删掉（YYDS 就是），
   * 于是**每点一次测试就消耗一个活跃邮箱名额**（用完即删）。
   * 连点由 `src/http/admin/probe-guard.ts` 那把共用的护栏挡着，这里不另造一套。
   *
   * @param domain 建东西时用哪个域名。由调用方从 `listDomains()` 的结果里取，
   *   **不在这里再列一次**——那会多打一次上游请求，而调用方手上已经有了。
   *   压根不需要建东西的实现忽略它。
   */
  verifyCredentials(domain: string): Promise<CredentialProof>;
}
